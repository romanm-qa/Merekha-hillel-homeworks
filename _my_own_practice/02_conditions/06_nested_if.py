# Вложенный if находится внутри блока другого условия.
# Проверка билета выполняется, только если возраст подходит.
age = 20
has_ticket = True

print("Вложенная проверка — возраст и билет:")
print(f"Исходный возраст: {age!r}")
print(f"Есть билет: {has_ticket!r}")
if age >= 18:
    if has_ticket:
        print("Вход разрешён")
    else:
        print("Нужен билет")
else:
    print("Вход только с 18 лет")

# Сначала проверяем диапазон, затем вычисляем y и определяем его знак.
# if/elif/else выбирает только один вариант знака.
x = 1

print("\nПроверка диапазона и знака результата:")
print(f"Исходное число x: {x!r}")
print("Допустимый диапазон: 0 <= x < 11")
if 0 <= x < 11:
    y = 3 * x - 6
    print(f"y = 3 * x - 6 -> {y!r}")

    if y < 0:
        print("y — отрицательное число")
    elif y > 0:
        print("y — положительное число")
    else:
        print("y равно нулю")
else:
    print("x не входит в допустимый диапазон")

# При ложном внешнем условии вложенная проверка не выполняется.
x = 15

print("\nЗначение вне диапазона:")
print(f"Исходное число x: {x!r}")
print("Допустимый диапазон: 0 <= x < 11")
if 0 <= x < 11:
    if x % 2 == 0:
        print("x входит в диапазон и является чётным")
    else:
        print("x входит в диапазон и является нечётным")
else:
    print("x не входит в диапазон: чётность не проверяем")

# Отступы определяют, к какому if относится else.
# Внутренний else обрабатывает отсутствие билета, внешний — возраст.
age = 20
has_ticket = False

print("\nВнутренний и внешний else:")
print(f"Исходный возраст: {age!r}")
print(f"Есть билет: {has_ticket!r}")
if age >= 18:
    if has_ticket:
        print("Вход разрешён")
    else:
        print("Возраст подходит, но билета нет")
else:
    print("Возраст не подходит")

# Если нужно только проверить выполнение обоих условий,
# вложенные if можно заменить одним условием с and.
age = 20
has_ticket = True

print("\nОбъединение условий через and:")
print(f"Исходный возраст: {age!r}")
print(f"Есть билет: {has_ticket!r}")
if age >= 18 and has_ticket:
    print("Вход разрешён")
else:
    print("Вход запрещён: возраст не подходит или билета нет")
