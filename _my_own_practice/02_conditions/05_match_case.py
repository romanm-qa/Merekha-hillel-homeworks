# match/case сопоставляет значение с образцами (шаблонами).
# В простых примерах образцы — конкретные числа или строки.
# Конструкция доступна начиная с Python 3.10.
choice = 2

print("Выбор варианта — match/case:")
print(f"Исходный выбор: {choice!r}")
match choice:
    case 1:
        print("Вы выбрали вариант 1")
    case 2:
        print("Вы выбрали вариант 2")
    case 3:
        print("Вы выбрали вариант 3")
    case _:
        print("Нет такой опции")

# Такой выбор можно записать через if/elif/else.
choice = 2

print("\nТа же проверка через if/elif/else:")
print(f"Исходный выбор: {choice!r}")
if choice == 1:
    print("Вы выбрали вариант 1")
elif choice == 2:
    print("Вы выбрали вариант 2")
elif choice == 3:
    print("Вы выбрали вариант 3")
else:
    print("Нет такой опции")

# case _ подходит для любого значения и служит запасным вариантом.
# Его ставим последним. Сам символ _ не сохраняет проверяемое значение.
choice = 10

print("\nЗначение без отдельного варианта — case _:")
print(f"Исходный выбор: {choice!r}")
match choice:
    case 1:
        print("Вы выбрали вариант 1")
    case 2:
        print("Вы выбрали вариант 2")
    case _:
        print("Нет такой опции")

# Если нет подходящего case и нет case _, ни один блок не выполнится.
command = "unknown"

print("\nНет совпадения и запасного варианта:")
print(f"Исходная команда: {command!r}")
match command:
    case "start":
        print("Запуск")
    case "stop":
        print("Остановка")
print("Выполнение продолжается после match")

# Через | можно объединить несколько образцов в одной ветке.
# Выполняется только первая подходящая ветка; break не нужен.
command = "exit"

print("\nНесколько вариантов в одном case:")
print(f"Исходная команда: {command!r}")
match command:
    case "start" | "run":
        print("Запуск")
    case "stop" | "exit":
        print("Остановка")
    case _:
        print("Неизвестная команда")

# Образцы 1 и "1" различаются: число и строка — разные значения.
# input() возвращает строку; для числового выбора нужно преобразование.
choice = "1"

print("\nЧисло и строка в образцах:")
print(f"Исходный выбор: {choice!r}")
match choice:
    case 1:
        print("Выбор передан числом")
    case "1":
        print("Выбор передан строкой")
    case _:
        print("Нет такой опции")

# Обычное имя в case захватывает значение, а не сравнивает с переменной.
# Для строкового варианта пишем case "start", а не case start.
