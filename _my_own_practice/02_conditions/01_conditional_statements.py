# if выполняет свой блок, если условие истинно.
# После условия ставим двоеточие, блок выделяем отступом в 4 пробела.
age = 20

print("Проверка условия — if:")
print(f"Исходный возраст: {age!r}")
print(f"age >= 18 -> {age >= 18!r}")
if age >= 18:
    print("Доступ разрешён")

# else выполняется, если условие if ложно.
age = 16

print("\nВыбор из двух вариантов — if/else:")
print(f"Исходный возраст: {age!r}")
if age >= 18:
    print("Доступ разрешён")
else:
    print("Доступ запрещён")

# elif проверяет следующее условие, если предыдущие были ложными.
# Выполняется только первая подходящая ветка всей цепочки.
score = 85

print("\nНесколько вариантов — if/elif/else:")
print(f"Исходные баллы: {score!r}")
if score >= 90:
    print("Отлично")
elif score >= 75:
    print("Хорошо")
elif score >= 60:
    print("Зачтено")
else:
    print("Не зачтено")

# Отдельные if проверяются независимо: могут выполниться несколько блоков.
number = 12

print("\nНезависимые проверки — несколько if:")
print(f"Исходное число: {number!r}")
if number > 0:
    print("Число положительное")
if number % 2 == 0:
    print("Число чётное")

# В цепочке if/elif выполняется только первая подходящая ветка.
number = 12

print("\nТе же условия в цепочке if/elif:")
print(f"Исходное число: {number!r}")
if number > 0:
    print("Число положительное")
elif number % 2 == 0:
    print("Число чётное")

# else относится к своему if на том же уровне отступа.
# Здесь else связан со вторым if.
number = 5

print("\nК какому if относится else:")
print(f"Исходное число: {number!r}")
if number > 0:
    print("Число положительное")
if number % 2 == 0:
    print("Число чётное")
else:
    print("Число нечётное")

# pass — инструкция-заглушка: ничего не делает.
# Она позволяет оставить синтаксически обязательный блок без действий.
age = 20

print("\nПустой блок — pass:")
print(f"Исходный возраст: {age!r}")
if age >= 18:
    pass
print("Выполнение продолжается после if")
