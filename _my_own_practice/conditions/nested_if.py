# Nested if (вложенные условные конструкции)
#
# Вложенный if используется, когда вторую проверку нужно выполнять
# только после успешного прохождения первой.
#
# В данном примере:
# 1. Проверяем, входит ли x в заданный диапазон.
# 2. Если входит — вычисляем y.
# 3. Затем определяем знак числа y (отрицательное, положительное или 0).
# 4. Дополнительно выполняются независимые проверки x.
#
# Важно:
# if может находиться внутри другого if.
# Также несколько if могут быть независимыми друг от друга.

x = int(input('x = '))

if 0 <= x < 11:
    print('Значення x входить в даний діапазон, продовжуєм')

    y = 3 * x - 6

    if y < 0:
        print('Значення y відємне')

    if y > 0:
        print('Значення y позитивне')
    else:
        print('y = 0')

if x == 10:
    print('hello')

if x == 100:
    print('world')
else:
    print('не попалі')