# Python - язык с динамической типизацией.
# Переменная может менять свой тип во время выполнения программы.

some_var = 123
print(some_var, type(some_var))

some_var = 0.6
print(some_var, type(some_var))

some_var = "Hello world"
print(some_var, type(some_var))

some_var = True
print(some_var, type(some_var))