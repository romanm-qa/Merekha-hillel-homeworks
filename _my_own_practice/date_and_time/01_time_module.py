import time

# ============================================================
# 1. UNIX TIMESTAMP — КОЛИЧЕСТВО СЕКУНД С 1 ЯНВАРЯ 1970 ГОДА
# ============================================================
# time.time()
# │    └──── функция time()
# └───────── модуль time
# time.time() возвращает текущее время в виде количества секунд,
# прошедших с 1 января 1970 года, 00:00:00 UTC.
# Целая часть результата — секунды, дробная часть — доли секунды.

current_timestamp = time.time()

print("Текущий Unix timestamp:")
print(current_timestamp)

# ============================================================
# 2. TIME.SLEEP() — ПАУЗА В ВЫПОЛНЕНИИ ПРОГРАММЫ
# ============================================================

# time.sleep(seconds) останавливает выполнение программы
# на указанное количество секунд.
#
# Во время паузы программа ничего не проверяет и просто ждёт.
# Поэтому в реальных автотестах sleep() нужно использовать осторожно.

print("\nНачало паузы")

time.sleep(2)

print("Пауза закончилась: прошло примерно 2 секунды")

# ============================================================
# 3. TIME.MONOTONIC() — ИЗМЕРЕНИЕ ВРЕМЕННЫХ ИНТЕРВАЛОВ
# ============================================================

# time.monotonic() возвращает значение внутренних монотонных часов.
# Его значение подходит не для определения текущей даты,
# а для измерения продолжительности выполнения программы.
#
# Монотонные часы движутся только вперёд.
# Они не зависят от изменения системного времени на компьютере.

start_tine = time.monotonic()

time.sleep(2)

end_tine = time.monotonic()

elapsed_time = end_tine - start_tine

print("\nИзмерение временного интервала:")
print(f"Прошло секунд: {elapsed_time:.2f}")

# ============================================================
# 4. TIME.LOCALTIME() — ПОЛУЧЕНИЕ КОМПОНЕНТОВ ЛОКАЛЬНОГО ВРЕМЕНИ
# ============================================================

# time.localtime() получает локальные дату и время компьютера
# и возвращает объект struct_time.
#
# В нём дата и время разделены на отдельные компоненты:
# год, месяц, день, часы, минуты и секунды.

local_time = time.localtime()

print("\nЛокальное время в формате struct_time:")
print(local_time)

print("\nОтдельные компоненты локального времени:")
print(f"Год: {local_time.tm_year}")
print(f"Месяц: {local_time.tm_mon}")
print(f"День: {local_time.tm_mday}")
print(f"Часы: {local_time.tm_hour}")
print(f"Минуты: {local_time.tm_min}")
print(f"Секунды: {local_time.tm_sec}")
