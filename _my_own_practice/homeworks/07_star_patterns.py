# 9, 14 — ромб и прямоугольный треугольник из звёздочек

# ==========================================
# Задача 9. Ромб из звёздочек
# ==========================================
# Дано целое положительное число n.
# Вывести ромб из звёздочек.
# Использовать циклы.

def print_diamond(n):
    for i in range(n):
        print(" " * (n - 1 - i) + "*" * (2 * i + 1))

    for i in range(n - 2, -1, -1):
        print(" " * (n - 1 - i) + "*" * (2 * i + 1))


print("=" * 50)
print("Задача 9. Ромб из звёздочек")
print("=" * 50)

print("n=1:")
print_diamond(1)
print()

print("n=3:")
print_diamond(3)
print()

print("n=5:")
print_diamond(5)
print()

print("n=7:")
print_diamond(7)
print()


# ==========================================
# Задача 14. Прямоугольный треугольник
# ==========================================
# Дано положительное целое число n.
# Вывести прямоугольный треугольник из звёздочек.
# Количество строк равно n.

def print_triangle(n):
    for i in range(1, n + 1):
        print("*" * i)


print("=" * 50)
print("Задача 14. Прямоугольный треугольник")
print("=" * 50)

print("n=1:")
print_triangle(1)
print()

print("n=3:")
print_triangle(3)
print()

print("n=5:")
print_triangle(5)
print()
