# ==========================================
# Задача 16. Високосный год
# ==========================================
# Дан год.
# Вернуть True, если год високосный, иначе — False.
#
# Год високосный, если:
# он делится на 400 без остатка
# ИЛИ делится на 4, но не делится на 100.

def is_leap_year(year):
    if year % 400 == 0:
        return True
    elif year % 4 == 0 and year % 100 != 0:
        return True
    else:
        return False


print("=" * 50)
print("Задача 16. Високосный год")
print("=" * 50)

print(f"Год: 2024 → високосный: {is_leap_year(2024)!r}")  # True
print(f"Год: 2025 → високосный: {is_leap_year(2025)!r}")  # False
print(f"Год: 1900 → високосный: {is_leap_year(1900)!r}")  # False
print(f"Год: 2000 → високосный: {is_leap_year(2000)!r}")  # True
print()


# ==========================================
# Практика. Бесплатная доставка
# ==========================================
# Функция принимает:
# order_total — сумму заказа;
# is_member — есть ли у покупателя подписка (True/False).
#
# Доставка бесплатная, если:
# сумма заказа не меньше 1000
# ИЛИ есть подписка и сумма заказа не меньше 500.
# Вернуть True, если доставка бесплатная, иначе — False.

def has_free_delivery(order_total, is_member):
    if order_total >= 1000:
        return True
    elif is_member == True and order_total >= 500:
        return True
    else:
        return False


print("=" * 50)
print("Практика. Бесплатная доставка")
print("=" * 50)

print(f"Заказ: 1200, подписка: False → бесплатно: {has_free_delivery(1200, False)!r}")
print(f"Заказ: 600, подписка: True → бесплатно: {has_free_delivery(600, True)!r}")
print(f"Заказ: 600, подписка: False → бесплатно: {has_free_delivery(600, False)!r}")
print(f"Заказ: 400, подписка: True → бесплатно: {has_free_delivery(400, True)!r}")
print(f"Заказ: 1000, подписка: False → бесплатно: {has_free_delivery(1000, False)!r}")
print(f"Заказ: 500, подписка: True → бесплатно: {has_free_delivery(500, True)!r}")
print()


# ==========================================
# Задача 17. Число между границами
# ==========================================
# Даны три целых числа: a, b и x.
# Вернуть True, если x находится строго между a и b.
# Иначе вернуть False.
# Границы могут идти в любом порядке.
# Если x равен одной из границ — вернуть False.

def is_between(a, b, x):
    if a < x < b or b < x < a:
        return True
    else:
        return False


print("=" * 50)
print("Задача 17. Число между границами")
print("=" * 50)

print(f"a=1, b=10, x=5 → между: {is_between(1, 10, 5)!r}")
print(f"a=10, b=1, x=5 → между: {is_between(10, 1, 5)!r}")
print(f"a=1, b=10, x=1 → между: {is_between(1, 10, 1)!r}")
print(f"a=1, b=10, x=12 → между: {is_between(1, 10, 12)!r}")
