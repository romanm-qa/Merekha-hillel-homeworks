# ==========================================
# Задача 2. Цвета шахматных клеток
# ==========================================
# Даны координаты двух клеток шахматной доски:
# x1, y1 — столбец и строка первой клетки;
# x2, y2 — столбец и строка второй клетки.
# Все координаты — целые числа от 1 до 8.
# Вернуть "YES", если клетки одного цвета, иначе — "NO".

def compare_cell_colors(x1, y1, x2, y2):
    first_square_sum = x1 + y1
    second_square_sum = x2 + y2

    if first_square_sum % 2 == second_square_sum % 2:
        return "YES"
    else:
        return "NO"


print("=" * 50)
print("Задача 2. Цвета шахматных клеток")
print("=" * 50)

print(f"Клетки: (1, 1), (2, 2) → {compare_cell_colors(1, 1, 2, 2)!r}")  # YES
print(f"Клетки: (1, 2), (2, 3) → {compare_cell_colors(1, 2, 2, 3)!r}")  # YES
print(f"Клетки: (1, 1), (1, 2) → {compare_cell_colors(1, 1, 1, 2)!r}")  # NO
print(f"Клетки: (1, 2), (1, 1) → {compare_cell_colors(1, 2, 1, 1)!r}")  # NO
print()


