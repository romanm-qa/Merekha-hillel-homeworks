import random


# 22 — игра «Угадай число»

# ==========================================
# Задача 22. Игра «Угадай число»
# ==========================================
# Сгенерировать случайное число от 1 до 10.
# Попросить пользователя угадать число.
# Вывести сообщение о результате.
# Пользователю даётся одна попытка.

def guess_number():
    secret_number = random.randint(1, 10)

    user_guess = int(input("Твой выбор: "))

    if user_guess == secret_number:
        print("Ты угадал число!")
    else:
        print(f"Не угадал! Загаданное число: {secret_number}")


print("=" * 50)
print("Задача 22. Игра «Угадай число»")
print("=" * 50)

guess_number()
print()
