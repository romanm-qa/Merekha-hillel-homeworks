# ==========================================
# Практика. Распределение конфет
# ==========================================
# Даны два целых числа:
# candies — количество конфет;
# children — количество детей.
#
# Разделить конфеты поровну между детьми.
# Вывести, сколько конфет получит каждый ребёнок,
# и сколько конфет останется.
# Учесть, что количество детей не может быть равно нулю.

def distribute_candies(candies, children):
    if children == 0:
        return "Количесво детей не может равняться 0"
    elif candies % children == 0:
        return f"Каждый ребенок получит {candies // children} конфеты"
    else:
        return f"Каждый ребенок получит по {candies // children} конфет. А остаток конфет: {candies % children}"


print("=" * 50)
print("Практика. Распределение конфет")
print("=" * 50)

print(f"candies=20, children=5 → {distribute_candies(20, 5)!r}")
print(f"candies=17, children=5 → {distribute_candies(17, 5)!r}")
print(f"candies=3, children=5 → {distribute_candies(3, 5)!r}")
print(f"candies=10, children=0 → {distribute_candies(10, 0)!r}")
print()


# ==========================================
# Практика. Упаковка товаров
# ==========================================
# Дано количество товаров и вместимость одной коробки.
# Определить, сколько полных коробок можно заполнить
# и сколько товаров останется.
# Если товары остались, определить, сколько ещё
# товаров нужно для заполнения следующей коробки.
# Учесть, что вместимость коробки не может быть равна нулю.

def pack_items(items, capacity):
    if capacity == 0:
        return "Вместимость коробки не должна равняться 0"
    elif items % capacity == 0:
        return f"{items // capacity} коробок можно заполнить"
    else:
        return (f"Получилось {items // capacity} полных коробок. "
                f"Остаток товаров: {items % capacity}. "
                f"{capacity - items % capacity} нужно товаров для следующей коробки.")


print("=" * 50)
print("Практика. Упаковка товаров")
print("=" * 50)

print(f"items=20, capacity=5 → {pack_items(20, 5)!r}")
print(f"items=17, capacity=5 → {pack_items(17, 5)!r}")
print(f"items=3, capacity=5 → {pack_items(3, 5)!r}")
print(f"items=10, capacity=0 → {pack_items(10, 0)!r}")
print()


# ==========================================
# Задача 18. Расстояние между двумя точками
# ==========================================
# Даны четыре действительных числа: x1, y1, x2, y2.
# Вычислить расстояние между точками (x1, y1) и (x2, y2).
# Считать четыре действительных числа и вывести
# результат работы этой функции.

def calculate_distance(x1, y1, x2, y2):
    difference_x = x1 - x2
    difference_y = y1 - y2
    sum_of_squares = difference_x ** 2 + difference_y ** 2

    return sum_of_squares ** 0.5


print("=" * 50)
print("Задача 18. Расстояние между двумя точками")
print("=" * 50)

print(f"A=(1, 1), B=(5, 4) → {calculate_distance(1, 1, 5, 4)!r}")
print(f"A=(0, 0), B=(3, 4) → {calculate_distance(0, 0, 3, 4)!r}")
print(f"A=(2, 3), B=(2, 3) → {calculate_distance(2, 3, 2, 3)!r}")
print(f"A=(-1, -2), B=(2, 2) → {calculate_distance(-1, -2, 2, 2)!r}")
