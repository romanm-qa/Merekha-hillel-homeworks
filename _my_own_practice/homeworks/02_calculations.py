# ==========================================
# Практика. Деление числа нацело
# ==========================================
# Даны два целых числа.
# Проверить, можно ли разделить первое число на второе без остатка.
# Если можно — вывести частное.
# Если нельзя — вывести, сколько нужно прибавить к первому числу,
# чтобы оно делилось на второе без остатка.
# Учесть деление на ноль.

def check_division(a, b):
    if b == 0:
        return "На 0 делить нельзя"
    elif a % b == 0:
        return f"Частное: {a // b}"
    else:
        return f"Нужно прибавить: {b - a % b}"


print("=" * 50)
print("Практика. Деление числа нацело")
