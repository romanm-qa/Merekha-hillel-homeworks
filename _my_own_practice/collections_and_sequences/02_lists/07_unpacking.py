# ==========================================
# РАСПАКОВКА СПИСКА
# ==========================================
# Распаковка позволяет присвоить элементы списка
# отдельным переменным за одну операцию.
# Количество переменных должно совпадать
# с количеством элементов списка.

print("=== Простая распаковка списка ===")

numbers = [10, 20, 30]

first, second, third = numbers

print("First:", first)
print("Second:", second)
print("Third:", third)

# ==========================================
# РАСПАКОВКА НАПРЯМУЮ
# ==========================================
# Можно распаковывать список без создания
# отдельной переменной.

print("\n=== Распаковка напрямую ===")

name, age = ["Roman", 29]

print("Name:", name)
print("Age:", age)

# ==========================================
# ОБМЕН ЗНАЧЕНИЙ ПЕРЕМЕННЫХ
# ==========================================
# В Python можно менять значения переменных
# местами без использования временной переменной.

print("\n=== Обмен значений ===")

a = 5
b = 17

print("До обмена:")
print("a =", a)
print("b =", b)

a, b = b, a

print("После обмена:")
print("a =", a)
print("b =", b)

# ==========================================
# РАСПАКОВКА СО ЗВЕЗДОЧКОЙ (*)
# ==========================================
# Символ * собирает все оставшиеся элементы
# списка в новый список.

print("\n=== Распаковка со звездочкой ===")

numbers = [10, 20, 30, 40, 50]

first, *middle, last = numbers

print("First:", first)
print("Middle:", middle)
print("Last:", last)

# ==========================================
# ИГНОРИРОВАНИЕ ЭЛЕМЕНТОВ
# ==========================================
# Если какой-то элемент нам не нужен,
# его принято записывать в переменную "_".

print("\n=== Игнорирование элементов ===")

numbers = [10, 20, 30]

first, _, third = numbers

print("First:", first)
print("Third:", third)
