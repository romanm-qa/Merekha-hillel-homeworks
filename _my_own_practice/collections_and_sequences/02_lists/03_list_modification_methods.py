# ==========================================
# МЕТОД append()
# ==========================================
# Метод append() добавляет объект в конец списка.
# Если передать другой список, range() или любой
# другой объект, он будет добавлен как один элемент.

print("=== Метод append() ===")

numbers = [1, 3, 5]

numbers.append(range(5))

print(numbers)

# ==========================================
# МЕТОД extend()
# ==========================================
# Метод extend() добавляет каждый элемент
# итерируемого объекта в конец списка.

print("\n=== Метод extend() ===")

numbers = [1, 3, 5]

numbers.extend(range(5))

print(numbers)

print("\n=== Сравнение append() и extend() ===")

numbers = [1, 2]

numbers.append([3, 4])
print("append():", numbers)

numbers = [1, 2]

numbers.extend([3, 4])
print("extend():", numbers)

# ==========================================
# МЕТОД insert()
# ==========================================
# Метод insert() вставляет элемент
# в указанную позицию списка.
# Остальные элементы сдвигаются вправо.

print("\n=== Метод insert() ===")

numbers = [1, 3, 5]

numbers.insert(1, 8)

print(numbers)

# ==========================================
# МЕТОД remove()
# ==========================================
# Метод remove() удаляет первое найденное
# значение из списка.
# Указывается не индекс, а сам элемент.

print("\n=== Метод remove() ===")

numbers = [1, 8, 3, 5, 3]

numbers.remove(3)

print(numbers)

# ==========================================
# МЕТОД pop()
# ==========================================
# Метод pop() удаляет элемент
# и одновременно возвращает его.
# По умолчанию удаляется последний элемент.

print("\n=== Метод pop() ===")

numbers = [10, 20, 30, 40]

deleted_item = numbers.pop()

print("Удаленный элемент:", deleted_item)
print("Список:", numbers)

print("\n=== pop() по индексу ===")

numbers = [10, 20, 30, 40]

deleted_item = numbers.pop(1)

print("Удаленный элемент:", deleted_item)
print("Список:", numbers)

# ==========================================
# МЕТОД clear()
# ==========================================
# Метод clear() удаляет все элементы списка.
# После вызова метода список становится пустым.

print("\n=== Метод clear() ===")

numbers = [10, 20, 30, 40]

numbers.clear()

print(numbers)
