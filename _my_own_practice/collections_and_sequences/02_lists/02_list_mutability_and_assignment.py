# ==========================================
# МУТАБЕЛЬНОСТЬ СПИСКОВ
# ==========================================
# Списки (list) являются изменяемым (mutable) типом данных.
# Это означает, что после создания списка его элементы
# можно изменять, добавлять или удалять.

print("=== Мутабельность списков ===")

fruits = ["apple", "banana", "orange"]

fruits[1] = "pear"
print(fruits)

# ==========================================
# УДАЛЕНИЕ ЭЛЕМЕНТОВ (del)
# ==========================================
# Оператор del удаляет элемент по индексу
# или сразу несколько элементов с помощью среза.
# После удаления длина списка уменьшается.

print("\n=== Удаление элементов (del) ===")

numbers = [10, 20, 30, 40, 50]

del numbers[2]
print(numbers)

del numbers[-1]
print(numbers)

del numbers[1:3]
print(numbers)

# ==========================================
# ПРИСВАИВАНИЕ (=)
# ==========================================
# Оператор "=" не создает новый список.
# Он лишь создает новую переменную,
# которая ссылается на тот же объект в памяти.
# Поэтому изменения через одну переменную
# будут видны и через другую.

print("\n=== Присваивание списка (=) ===")

original_list = [1, 2, 3]

shared_list = original_list

shared_list.append(4)

print("Original list:", original_list)
print("Shared list:  ", shared_list)

# ==========================================
# КОПИРОВАНИЕ СПИСКА (copy)
# ==========================================
# Метод copy() создает новый независимый список.
# После копирования изменения в копии
# не влияют на исходный список.

print("\n=== Копирование списка (copy) ===")

original_list = [1, 2, 3]

copied_list = original_list.copy()

copied_list.append(4)

print("Original list:", original_list)
print("Copied list:  ", copied_list)