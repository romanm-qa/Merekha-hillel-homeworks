# ==========================================
# СОЗДАНИЕ СПИСКА (List Creation)
# ==========================================

numbers = [10, 20, 30, 40, 50]
print(numbers)

fruits = ["apple", "banana", "orange"]
print(fruits)

mixed = [1, "Python", 3.14, True]
print(mixed)

empty_list = []
print(empty_list)

print(30 * "-")

# ==========================================
# ДОСТУП ПО ИНДЕКСУ (Indexing)
# ==========================================

fruits = ["apple", "banana", "orange", "kiwi"]

print(fruits[0])  # Первый элемент
print(fruits[1])  # Второй элемент
print(fruits[3])  # Последний по обычному индексу

print(30 * "-")

# ==========================================
# ОТРИЦАТЕЛЬНЫЕ ИНДЕКСЫ
# ==========================================

print(fruits[-1])  # Последний элемент
print(fruits[-2])  # Предпоследний элемент
print(fruits[-3])  # Третий с конца

print(30 * "-")

# ==========================================
# ИЗМЕНЕНИЕ ЭЛЕМЕНТА ПО ИНДЕКСУ
# ==========================================

fruits[1] = "pear"
print(fruits)

print(30 * "-")

# ==========================================
# СРЕЗЫ (Slicing)
# ==========================================

numbers = [10, 20, 30, 40, 50, 60]

print(numbers[1:4])  # Элементы с индексами 1-3
print(numbers[:3])  # Первые три элемента
print(numbers[2:])  # От третьего элемента до конца
print(numbers[:])  # Копия списка

print(30 * "-")

# ==========================================
# СРЕЗ С ШАГОМ
# ==========================================

print(numbers[::2])  # Каждый второй элемент
print(numbers[1::2])  # Каждый второй, начиная с индекса 1

print(30 * "-")

# ==========================================
# РАЗВОРОТ СПИСКА ЧЕРЕЗ СРЕЗ
# ==========================================

print(numbers[::-1])  # Список в обратном порядке
