# ==========================================
# МЕТОД index()
# ==========================================
# Метод index() возвращает индекс первого
# найденного элемента в списке.
# Если элемент отсутствует, возникнет ошибка ValueError.

print("=== Метод index() ===")

fruits = ["apple", "banana", "orange", "banana"]

print("Индекс 'banana':", fruits.index("banana"))
print("Индекс 'orange':", fruits.index("orange"))

# ==========================================
# МЕТОД count()
# ==========================================
# Метод count() подсчитывает,
# сколько раз элемент встречается в списке.

print("\n=== Метод count() ===")

numbers = [10, 20, 30, 20, 40, 20]

print("Количество 20:", numbers.count(20))
print("Количество 10:", numbers.count(10))
print("Количество 50:", numbers.count(50))

# ==========================================
# ОПЕРАТОР in
# ==========================================
# Оператор in проверяет,
# содержится ли элемент в списке.
# Возвращает True или False.

print("\n=== Оператор in ===")

fruits = ["apple", "banana", "orange"]

print("banana" in fruits)
print("kiwi" in fruits)
