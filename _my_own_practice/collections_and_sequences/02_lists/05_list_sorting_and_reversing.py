# ==========================================
# МЕТОД sort()
# ==========================================
# Метод sort() сортирует элементы исходного списка.
# Сам список изменяется, а метод ничего не возвращает.
# По умолчанию сортировка идет по возрастанию.

print("=== Метод sort() ===")

numbers = [5, 2, 8, 1, 3]

numbers.sort()

print("Отсортированный список:", numbers)

# ==========================================
# СОРТИРОВКА ПО УБЫВАНИЮ
# ==========================================
# Параметр reverse=True меняет направление сортировки.
# Элементы располагаются от большего к меньшему.

print("\n=== sort(reverse=True) ===")

descending_numbers = [5, 2, 8, 1, 3]

descending_numbers.sort(reverse=True)

print("Список по убыванию:", descending_numbers)

# ==========================================
# ФУНКЦИЯ sorted()
# ==========================================
# Функция sorted() возвращает новый отсортированный список.
# Исходная коллекция при этом не изменяется.

print("\n=== Функция sorted() ===")

original_numbers = [5, 2, 8, 1, 3]

sorted_numbers = sorted(original_numbers)

print("Исходный список:", original_numbers)
print("Новый список:   ", sorted_numbers)

# ==========================================
# СРАВНЕНИЕ sort() И sorted()
# ==========================================
# sort() изменяет исходный список.
# sorted() создает новый список и сохраняет исходный.

print("\n=== Сравнение sort() и sorted() ===")

first_list = [3, 1, 2]
second_list = [3, 1, 2]

first_list.sort()
new_list = sorted(second_list)

print("После sort():    ", first_list)
print("Исходный список:", second_list)
print("После sorted():  ", new_list)

# ==========================================
# МЕТОД reverse()
# ==========================================
# Метод reverse() разворачивает текущий порядок элементов.
# Он не сортирует значения, а просто меняет их местами
# относительно исходного порядка.

print("\n=== Метод reverse() ===")

numbers_to_reverse = [10, 20, 30, 40]

numbers_to_reverse.reverse()

print("Развернутый список:", numbers_to_reverse)

# ==========================================
# ФУНКЦИЯ reversed()
# ==========================================
# Функция reversed() не изменяет исходный список.
# Она возвращает специальный итерируемый объект.
# Чтобы увидеть результат как список, используем list().

print("\n=== Функция reversed() ===")

original_list = [10, 20, 30, 40]

reversed_list = list(reversed(original_list))

print("Исходный список:", original_list)
print("Новый список:   ", reversed_list)

# ==========================================
# СРЕЗ [::-1]
# ==========================================
# Срез [::-1] также создает новый список
# с элементами в обратном порядке.
# Исходный список не изменяется.

print("\n=== Разворот через срез [::-1] ===")

source_list = [10, 20, 30, 40]

sliced_list = source_list[::-1]

print("Исходный список:", source_list)
print("Новый список:   ", sliced_list)
