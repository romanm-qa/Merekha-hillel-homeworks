# =====================================================
# Метод find()
#
# Ищет первое вхождение указанной подстроки.
#
# Если подстрока найдена:
#     возвращает индекс первого символа.
#
# Если подстрока не найдена:
#     возвращает -1.
# =====================================================

text = "SADDSSAaasdas"

# Ищем первое вхождение символа "S"
print(text.find("S"))  # 0

# Ищем первое вхождение символа "A"
print(text.find("A"))  # 1

# Ищем первое вхождение подстроки
print(text.find("SSA"))  # 4

# Если символ не найден — получаем -1
print(text.find("Z"))  # -1

# Исходная строка не изменилась
print(text)

print("-" * 30)

# =====================================================
# Метод rfind()
#
# Ищет последнее вхождение подстроки.
#
# Поиск начинается с конца строки,
# но возвращается индекс относительно начала строки.
#
# Если ничего не найдено — возвращает -1.
# =====================================================

some_text = "abc abc abc"

print(some_text.rfind("abc"))   # 8
print(some_text.rfind("b"))     # 9
print(some_text.rfind("Z"))     # -1

print("-" * 30)

# =====================================================
# Метод index()
#
# Работает так же, как find(),
# но если подстрока не найдена,
# выбрасывает исключение ValueError.
# =====================================================

textik = "Hello"

print(textik.index("e"))   # 1

try:
    print(textik.index("X"))
except ValueError:
    print("Подстрока не найдена.")

# =====================================================
# Метод startswith()
#
# Проверяет, начинается ли строка
# с указанной подстроки.
#
# Возвращает:
# True  - если начинается.
# False - если не начинается.
# =====================================================

print("-" * 30)

textel = "Hello World"

print(textel.startswith("Hello"))   # True
print(textel.startswith("World"))   # False
print(textel.startswith("H"))       # True

print("-" * 30)

# =====================================================
# Метод endswith()
#
# Проверяет, заканчивается ли строка
# указанной подстрокой.
#
# Возвращает:
# True  - если заканчивается.
# False - если не заканчивается.
# =====================================================

report = "report.pdf"

print(report.endswith(".pdf"))   # True
print(report.endswith(".docx"))  # False
print(report.endswith("pdf"))    # True

print("-" * 30)
