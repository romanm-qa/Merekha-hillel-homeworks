# =====================================================
# Метод lower()
#
# Возвращает новую строку, в которой все символы
# преобразованы в нижний регистр.
#
# Исходная строка НЕ изменяется.
# =====================================================

text = "HeLLo WoRLD"

print(text)

print("-" * 30)

# Все символы становятся маленькими
print(text.lower())

print("-" * 30)

# =====================================================
# Метод upper()
#
# Возвращает новую строку, в которой все символы
# преобразованы в верхний регистр.
#
# Исходная строка НЕ изменяется.
# =====================================================

print(text.upper())

print("-" * 30)

# =====================================================
# Важно!
#
# Методы lower() и upper() НЕ изменяют строку.
# Они создают новую строку и возвращают её.
# =====================================================

some_text = "Python"

print(f"Исходная строка: {some_text}")

new_text = some_text.lower()

print(f"Новая строка: {new_text}")

print(f"Исходная строка после lower(): {some_text}")